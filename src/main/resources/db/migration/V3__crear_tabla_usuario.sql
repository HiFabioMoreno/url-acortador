CREATE TABLE usuario (
                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         external_id VARCHAR(255) NOT NULL,
                         email       VARCHAR(255),
                         CONSTRAINT uk_usuario_external_id UNIQUE (external_id)
);

ALTER TABLE url
    ADD COLUMN usuario_id BIGINT,
    ADD CONSTRAINT fk_url_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id);