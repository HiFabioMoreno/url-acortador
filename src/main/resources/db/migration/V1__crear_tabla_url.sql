CREATE TABLE url (
                     id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     original_url        VARCHAR(2048) NOT NULL,
                     slug                VARCHAR(255)  NOT NULL,
                     titulo              VARCHAR(255),
                     fecha_registro      VARCHAR(255)  NOT NULL,
                     fecha_modificacion  VARCHAR(255)  NOT NULL,
                     clicks              INTEGER       NOT NULL DEFAULT 0,

                     CONSTRAINT uk_url_original_url UNIQUE (original_url),
                     CONSTRAINT uk_url_slug         UNIQUE (slug),
                     CONSTRAINT ck_url_clicks       CHECK (clicks >= 0)
);